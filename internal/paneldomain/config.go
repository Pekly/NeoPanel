package paneldomain

import (
	"errors"
	"fmt"
	"net"
	"regexp"
	"strconv"
	"strings"
)

const maxAliases = 8

var labelRE = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$`)
var emailLocalRE = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._+%-]{0,63}$`)

// Deliberately accept only ASCII DNS names and a conservative email subset.
// In particular no Caddy substitution, quoting, comments or address syntax is allowed.
func validHostname(s string) bool {
	if len(s) > 253 || s != strings.ToLower(s) || net.ParseIP(s) != nil {
		return false
	}
	labels := strings.Split(s, ".")
	if len(labels) < 2 {
		return false
	}
	for _, label := range labels {
		if !labelRE.MatchString(label) {
			return false
		}
	}
	tld := labels[len(labels)-1]
	return strings.ContainsAny(tld, "abcdefghijklmnopqrstuvwxyz")
}

func validEmail(s string) bool {
	if len(s) > 254 || strings.Count(s, "@") != 1 {
		return false
	}
	parts := strings.SplitN(s, "@", 2)
	return emailLocalRE.MatchString(parts[0]) && !strings.Contains(parts[0], "..") && !strings.HasSuffix(parts[0], ".") && validHostname(parts[1])
}

func legacyBlock(host, email, upstream string) string {
	return fmt.Sprintf("%s {\n    encode gzip zstd\n    tls %s\n\n    reverse_proxy %s {\n        header_up Host {host}\n        header_up X-Real-IP {remote_host}\n    }\n}\n", host, email, upstream)
}

func aliasBlock(host, email, upstream string) string {
	return fmt.Sprintf("\n%s {\n    encode gzip zstd\n    tls {\n        issuer acme {\n            dir https://acme-v02.api.letsencrypt.org/directory\n            email %s\n        }\n    }\n\n    reverse_proxy %s {\n        header_up Host {host}\n        header_up X-Real-IP {remote_host}\n    }\n}\n", host, email, upstream)
}

// Recognize bytes generated by install.sh, then only our exact canonical blocks.
// This is intentionally NOT a parser for arbitrary Caddyfiles.
func parseConfig(data []byte, upstream string) ([]string, error) {
	s := string(data)
	lines := strings.Split(s, "\n")
	unsupported := errors.New("unsupported Caddyfile: expected the exact installer template and canonical managed aliases")
	if len(lines) < 10 {
		return nil, unsupported
	}
	host := strings.TrimSuffix(lines[0], " {")
	email := strings.TrimPrefix(lines[2], "    tls ")
	if !validHostname(host) || !validEmail(email) {
		return nil, unsupported
	}
	prefix := legacyBlock(host, email, upstream)
	if !strings.HasPrefix(s, prefix) {
		return nil, fmt.Errorf("%w (including listener/upstream mismatch)", unsupported)
	}
	hosts := []string{host}
	s = strings.TrimPrefix(s, prefix)
	for s != "" {
		if len(hosts) > maxAliases {
			return nil, errors.New("too many managed aliases")
		}
		lines = strings.Split(s, "\n")
		if len(lines) < 16 {
			return nil, unsupported
		}
		host = strings.TrimSuffix(lines[1], " {")
		email = strings.TrimPrefix(lines[6], "            email ")
		if !validHostname(host) || !validEmail(email) {
			return nil, unsupported
		}
		block := aliasBlock(host, email, upstream)
		if !strings.HasPrefix(s, block) {
			return nil, unsupported
		}
		for _, old := range hosts {
			if old == host {
				return nil, errors.New("duplicate configured hostname")
			}
		}
		hosts = append(hosts, host)
		s = strings.TrimPrefix(s, block)
	}
	return hosts, nil
}

func listenerUpstream(host string, port int, panel, behindProxy bool) (string, error) {
	if !panel || !behindProxy || host != "127.0.0.1" || port < 1 || port > 65535 {
		return "", errors.New("requires a panel behind_proxy listener on 127.0.0.1 with a valid port")
	}
	return "127.0.0.1:" + strconv.Itoa(port), nil
}
